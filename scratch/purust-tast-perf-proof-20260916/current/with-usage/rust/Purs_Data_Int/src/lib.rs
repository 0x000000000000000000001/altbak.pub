pub fn Data_Int_toStringAs(radix: i64, n: i64) -> String {
    let s = if radix == 16 {
        format!("{:x}", n)
    } else if radix == 10 {
        format!("{}", n)
    } else if radix == 8 {
        format!("{:o}", n)
    } else if radix == 2 {
        format!("{:b}", n)
    } else {
        panic!("Unsupported radix: {}", radix);
    };
    s
}

