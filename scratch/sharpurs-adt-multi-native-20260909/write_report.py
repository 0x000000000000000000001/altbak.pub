"""Write the final empirical report only from completed, captured measurements."""
import json
import re
from common import AUDIT, LAZY, RBT, require, sha

result = json.loads((AUDIT / 'comparison.json').read_text())
inputs = json.loads((AUDIT / 'inputs.json').read_text())
inventory = json.loads((AUDIT / 'generation-inventory.json').read_text())
normal = json.loads((AUDIT / 'build-normal.json').read_text())
require(result['validation']['passed'] and result['validation']['official_processes_per_variant'] == 5,
        'Five completed measurement pairs are required')
require(normal['sourceSha256'] == inputs['afterSha256'] == inputs['sourceGeneratedSha256'],
        'Normal build must use the measured integration sources')

def metric(name):
    if name == 'total_ms':
        before = result['summaries']['before']['total_ms']
        after = result['summaries']['after']['total_ms']
        change = result['changes']['total_ms']
        scale = 1
    else:
        before = result['summaries']['before']['tests_us'][name]
        after = result['summaries']['after']['tests_us'][name]
        change = result['changes']['tests_us'][name]
        scale = 1000
    fmt = lambda value: f'{value / scale:.5f}'
    return {'before': fmt(before['median']), 'after': fmt(after['median']),
            'beforeRange': f"{fmt(before['min'])}–{fmt(before['max'])}",
            'afterRange': f"{fmt(after['min'])}–{fmt(after['max'])}",
            'change': f"{change['difference_percent']:+.2f}%"}

total, rbt, lazy = metric('total_ms'), metric(RBT), metric(LAZY)
build_rows = []
for stage in ['before', 'after', 'normal']:
    log = (AUDIT / f'build-{stage}.log').read_text()
    warnings = re.findall(r'(\d+) Warning\(s\)', log)[-1]
    errors = re.findall(r'(\d+) Error\(s\)', log)[-1]
    elapsed = re.findall(r'Time Elapsed (.+)', log)[-1]
    build_rows.append(f'| {stage} | {elapsed} | {warnings} | {errors} |')

validation_rows = []
for name, title in [('ins', 'Insertion'), ('tree', 'Tree / depth / makeBlack'),
                    ('balance', 'Balance'), ('lazy', 'Lazy'), ('codepoints', 'CodePoints')]:
    counts = []
    for stage in ['before', 'after']:
        log = (AUDIT / f'validation-{stage}-{name}.log').read_text()
        numbers = re.findall(r'(\d+) [^\n]*checks passed', log)
        require(numbers, f'Missing successful validation count: {stage}/{name}')
        counts.append(numbers[-1])
    validation_rows.append(f'| {title} | {counts[0]} | {counts[1]} |')

files = sorted({p for pattern in ['Verify*.fsx', 'validation-*.log', 'validation-oracle.before.json']
                for p in AUDIT.glob(pattern)} | {p for p in (AUDIT / 'adt-multi-validation').rglob('*') if p.is_file()})
(AUDIT / 'validation-files.json').write_text(json.dumps(
    {str(p.relative_to(AUDIT)): sha(p) for p in files}, indent=2) + '\n')
native_lines = []
for entry in inventory['files']:
    names = ', '.join('`' + name + '`' for name in entry['newNativeFunctionDeclarations']) or 'No new native declaration'
    native_lines.append(f"- `{entry['file']}`: {names}.")

